using Microsoft.EntityFrameworkCore;
using ScrumPilot.Data.Context;
using ScrumPilot.Shared.Models;

namespace ScrumPilot.Data.Repositories
{
    public class PbiRepository : IPbiRepository
    {
        private readonly ScrumPilotContext _context;

        public PbiRepository(ScrumPilotContext context)
        {
            _context = context;
        }

        public async Task<IEnumerable<ProductBacklogItem>> GetByProjectAsync(
            int projectId,
            bool? isDraft = null,
            CancellationToken cancellationToken = default)
        {
            var query = _context.Stories.Where(story => story.ProjectId == projectId);
            if (isDraft.HasValue)
                query = query.Where(story => story.IsDraft == isDraft.Value);
            return await query
                .OrderByDescending(s => s.DateCreated)
                .ToListAsync(cancellationToken);
        }

