using Microsoft.EntityFrameworkCore;
using ScrumPilot.Data.Context;
using ScrumPilot.Shared.Models;

namespace ScrumPilot.Data.Repositories
{
    public class PbiRepository : IPbiRepository
    {
        private readonly OrganizationContext _context;
        private readonly IPlanningMutationHandler? _planning;
        public ControlPlaneContext? Directory { get; init; }

        private async Task HydrateUsers(IEnumerable<ProductBacklogItem> items, CancellationToken ct)
        {
            if (Directory is null) return;
            var list = items.ToList();
            var ids = list.Where(x => x.AssignedToUserId != null).Select(x => x.AssignedToUserId!).Distinct().ToArray();
            var names = await Directory.Users.AsNoTracking().Where(u => ids.Contains(u.Id))
                .ToDictionaryAsync(u => u.Id, u => u.UserName, ct);
            foreach (var item in list) item.AssignedToUserName = item.AssignedToUserId is string id
                ? names.GetValueOrDefault(id) ?? "Former member" : null;
        }

        public PbiRepository(OrganizationContext context, IPlanningMutationHandler? planning = null)
        {
            _context = context;
            _planning = planning;
        }

        public async Task<IEnumerable<ProductBacklogItem>> GetByProjectAsync(
            int projectId,
            bool? isDraft = null,
            CancellationToken cancellationToken = default)
        {
            var query = _context.Stories.Where(story => story.ProjectId == projectId);
            if (isDraft.HasValue)
                query = query.Where(story => story.IsDraft == isDraft.Value);
            var items = await query
                .OrderByDescending(s => s.DateCreated)
                .ToListAsync(cancellationToken);
            await HydrateUsers(items, cancellationToken);
            return items;
        }

        public async Task<ProductBacklogItem?> GetByIdAsync(int id, CancellationToken cancellationToken = default)
        {
            var item = await _context.Stories
                .FirstOrDefaultAsync(s => s.PbiId == id, cancellationToken);
            if (item != null) await HydrateUsers([item], cancellationToken);
            return item;
        }

        public async Task<ProductBacklogItem> AddAsync(ProductBacklogItem story, CancellationToken cancellationToken = default)
        {
            // Note: Id will be auto-generated by the database (identity column)
            _context.Stories.Add(story);
            await SaveAsync(cancellationToken);
            await HydrateUsers([story], cancellationToken);
            return story;
        }

        public async Task<List<ProductBacklogItem>> AddRangeAsync(
            IEnumerable<ProductBacklogItem> stories,
            CancellationToken cancellationToken = default)
        {
            var items = stories.ToList();
            _context.Stories.AddRange(items);
            await SaveAsync(cancellationToken);
            await HydrateUsers(items, cancellationToken);
            return items;
        }

        public async Task<ProductBacklogItem> UpdateAsync(ProductBacklogItem story, CancellationToken cancellationToken = default)
        {
            await SaveAsync(cancellationToken);
            await HydrateUsers([story], cancellationToken);
            return story;
        }

        public async Task<bool> DeleteAsync(int id, CancellationToken cancellationToken = default)
        {
            var story = await _context.Stories.FindAsync([id], cancellationToken);
            if (story == null)
            {
                return false;
            }

            _context.Stories.Remove(story);
            await SaveAsync(cancellationToken);
            return true;
        }

        private Task SaveAsync(CancellationToken cancellationToken) =>
            _planning is not null ? _planning.SaveAsync(cancellationToken) : _context.SaveChangesAsync(cancellationToken);

        public async Task<IEnumerable<ProductBacklogItem>> GetFilteredPbisAsync(int? sprintId, int? epicId, int? projectId = null, CancellationToken cancellationToken = default)
        {
            var query = _context.Stories.Where(s => !s.IsDraft);

            if (projectId.HasValue)
                query = query.Where(s => s.ProjectId == projectId.Value);

            if (sprintId.HasValue)
            {
                if (sprintId.Value == -1)
                    query = query.Where(s => s.SprintId == null);
                else
                    query = query.Where(s => s.SprintId == sprintId.Value);
            }

            if (epicId.HasValue)
                query = query.Where(s => s.EpicId == epicId.Value);

            var items = await query
                .OrderByDescending(s => s.DateCreated)
                .ToListAsync(cancellationToken);
            await HydrateUsers(items, cancellationToken);
            return items;
        }
    }
}